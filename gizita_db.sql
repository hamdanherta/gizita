-- =============================================================
-- GIZITA DATABASE DUMP (PUSKESMAS KEBUN KOPI)
-- Dibuat otomatis untuk sinkronisasi GitHub & import lokal
-- =============================================================

CREATE DATABASE IF NOT EXISTS `gizita_db` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `gizita_db`;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS `pengaturan_sistem`;
CREATE TABLE IF NOT EXISTS `pengaturan_sistem` (`id` INTEGER auto_increment , `key` VARCHAR(100) NOT NULL UNIQUE, `value` TEXT, `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`)) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `puskesmas`;
CREATE TABLE IF NOT EXISTS `puskesmas` (`id` INTEGER auto_increment , `nama` VARCHAR(150) NOT NULL, `alamat` TEXT, `telepon` VARCHAR(30), `email` VARCHAR(100), `kepala` VARCHAR(150), `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`)) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `wilayah_posyandu`;
CREATE TABLE IF NOT EXISTS `wilayah_posyandu` (`id` INTEGER auto_increment , `puskesmas_id` INTEGER NOT NULL, `nama_posyandu` VARCHAR(150) NOT NULL, `kelurahan_desa` VARCHAR(100), `alamat` TEXT, `nama_kader` VARCHAR(150), `telepon_kader` VARCHAR(30), `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`puskesmas_id`) REFERENCES `puskesmas` (`id`) ON DELETE CASCADE ON UPDATE CASCADE) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `users`;
CREATE TABLE IF NOT EXISTS `users` (`id` INTEGER auto_increment , `nama` VARCHAR(150) NOT NULL, `username` VARCHAR(100) NOT NULL UNIQUE, `email` VARCHAR(150) NOT NULL UNIQUE, `password_hash` VARCHAR(255) NOT NULL, `role` ENUM('admin', 'petugas_gizi', 'dokter') NOT NULL DEFAULT 'petugas_gizi', `puskesmas_id` INTEGER, `no_hp` VARCHAR(30), `status_aktif` TINYINT(1) DEFAULT true, `last_login` DATETIME, `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`puskesmas_id`) REFERENCES `puskesmas` (`id`) ON DELETE SET NULL ON UPDATE CASCADE) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `who_lms`;
CREATE TABLE IF NOT EXISTS `who_lms` (`id` INTEGER auto_increment , `indikator` ENUM('BBU', 'TBU', 'BBPB', 'BBTB') NOT NULL, `jenis_kelamin` ENUM('L', 'P') NOT NULL, `umur_bulan_atau_tinggi` DECIMAL(6,2) NOT NULL COMMENT 'Bulan (0-60) untuk BBU/TBU, atau cm (45-120) untuk BBPB/BBTB', `l` DOUBLE PRECISION NOT NULL, `m` DOUBLE PRECISION NOT NULL, `s` DOUBLE PRECISION NOT NULL, `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`)) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `menu_makanan`;
CREATE TABLE IF NOT EXISTS `menu_makanan` (`id` INTEGER auto_increment , `nama_menu` VARCHAR(150) NOT NULL, `jenis` ENUM('PMT', 'MPASI', 'makanan_keluarga') NOT NULL DEFAULT 'PMT', `kelompok_umur` VARCHAR(50) COMMENT 'Contoh: 6-11 bulan, 12-23 bulan, 24-59 bulan', `bahan` TEXT, `energi_kkal` DECIMAL(6,2), `protein_g` DECIMAL(5,2), `lemak_g` DECIMAL(5,2), `karbohidrat_g` DECIMAL(5,2), `deskripsi` TEXT, `aktif` TINYINT(1) DEFAULT true, `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`)) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `orang_tua`;
CREATE TABLE IF NOT EXISTS `orang_tua` (`id` INTEGER auto_increment , `nama_ayah` VARCHAR(150), `nama_ibu` VARCHAR(150) NOT NULL, `nik` VARCHAR(30), `no_hp` VARCHAR(30), `alamat` TEXT, `pekerjaan` VARCHAR(100), `wilayah_posyandu_id` INTEGER, `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`wilayah_posyandu_id`) REFERENCES `wilayah_posyandu` (`id`) ON DELETE SET NULL ON UPDATE CASCADE) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `balita`;
CREATE TABLE IF NOT EXISTS `balita` (`id` INTEGER auto_increment , `orang_tua_id` INTEGER, `wilayah_posyandu_id` INTEGER NOT NULL, `nik` VARCHAR(30), `nama` VARCHAR(150) NOT NULL, `jenis_kelamin` ENUM('L', 'P') NOT NULL, `tanggal_lahir` DATE NOT NULL, `berat_lahir` DECIMAL(5,2), `panjang_lahir` DECIMAL(5,2), `anak_ke` INTEGER, `status_aktif` TINYINT(1) DEFAULT true, `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`orang_tua_id`) REFERENCES `orang_tua` (`id`) ON DELETE SET NULL ON UPDATE CASCADE, FOREIGN KEY (`wilayah_posyandu_id`) REFERENCES `wilayah_posyandu` (`id`) ON DELETE CASCADE ON UPDATE CASCADE) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `pengukuran`;
CREATE TABLE IF NOT EXISTS `pengukuran` (`id` INTEGER auto_increment , `balita_id` INTEGER NOT NULL, `tanggal_ukur` DATE NOT NULL, `umur_bulan` INTEGER NOT NULL, `berat_badan` DECIMAL(5,2) NOT NULL COMMENT 'Berat badan dalam kilogram (kg)', `tinggi_badan` DECIMAL(5,2) NOT NULL COMMENT 'Tinggi atau panjang badan dalam cm', `cara_ukur` ENUM('terlentang', 'berdiri') NOT NULL DEFAULT 'terlentang', `lingkar_kepala` DECIMAL(5,2) COMMENT 'Lingkar kepala dalam cm', `lila` DECIMAL(5,2) COMMENT 'Lingkar lengan atas dalam cm', `petugas_id` INTEGER, `posyandu_id` INTEGER, `catatan` TEXT, `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`balita_id`) REFERENCES `balita` (`id`) ON DELETE CASCADE ON UPDATE CASCADE, FOREIGN KEY (`petugas_id`) REFERENCES `users` (`id`) ON DELETE SET NULL ON UPDATE CASCADE, FOREIGN KEY (`posyandu_id`) REFERENCES `wilayah_posyandu` (`id`) ON DELETE SET NULL ON UPDATE CASCADE) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `status_gizi`;
CREATE TABLE IF NOT EXISTS `status_gizi` (`id` INTEGER auto_increment , `pengukuran_id` INTEGER NOT NULL, `balita_id` INTEGER NOT NULL, `zscore_bbu` DECIMAL(6,2), `zscore_tbu` DECIMAL(6,2), `zscore_bbtb` DECIMAL(6,2), `kategori_bbu` VARCHAR(50), `kategori_tbu` VARCHAR(50), `kategori_bbtb` VARCHAR(50), `status_final` VARCHAR(50), `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`pengukuran_id`) REFERENCES `pengukuran` (`id`) ON DELETE CASCADE ON UPDATE CASCADE, FOREIGN KEY (`balita_id`) REFERENCES `balita` (`id`) ON DELETE CASCADE ON UPDATE CASCADE) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `rencana_intervensi`;
CREATE TABLE IF NOT EXISTS `rencana_intervensi` (`id` INTEGER auto_increment , `balita_id` INTEGER NOT NULL, `status_gizi_id` INTEGER, `jenis_intervensi` ENUM('PMT', 'konseling', 'rujukan', 'suplemen', 'lainnya') NOT NULL DEFAULT 'PMT', `tujuan` VARCHAR(255), `target` VARCHAR(255), `tanggal_mulai` DATE NOT NULL, `tanggal_selesai` DATE, `status` ENUM('direncanakan', 'berjalan', 'selesai', 'dibatalkan') NOT NULL DEFAULT 'direncanakan', `dibuat_oleh` INTEGER, `catatan` TEXT, `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`balita_id`) REFERENCES `balita` (`id`) ON DELETE CASCADE ON UPDATE CASCADE, FOREIGN KEY (`status_gizi_id`) REFERENCES `status_gizi` (`id`) ON DELETE SET NULL ON UPDATE CASCADE, FOREIGN KEY (`dibuat_oleh`) REFERENCES `users` (`id`) ON DELETE SET NULL ON UPDATE CASCADE) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `jadwal_pmt`;
CREATE TABLE IF NOT EXISTS `jadwal_pmt` (`id` INTEGER auto_increment , `rencana_intervensi_id` INTEGER, `balita_id` INTEGER NOT NULL, `tanggal` DATE NOT NULL, `menu_id` INTEGER, `jumlah_porsi` INTEGER DEFAULT 1, `status` ENUM('terjadwal', 'diberikan', 'tidak_diberikan') NOT NULL DEFAULT 'terjadwal', `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`rencana_intervensi_id`) REFERENCES `rencana_intervensi` (`id`) ON DELETE SET NULL ON UPDATE CASCADE, FOREIGN KEY (`balita_id`) REFERENCES `balita` (`id`) ON DELETE CASCADE ON UPDATE CASCADE, FOREIGN KEY (`menu_id`) REFERENCES `menu_makanan` (`id`) ON DELETE SET NULL ON UPDATE CASCADE) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `konsumsi_pmt`;
CREATE TABLE IF NOT EXISTS `konsumsi_pmt` (`id` INTEGER auto_increment , `jadwal_pmt_id` INTEGER NOT NULL, `balita_id` INTEGER NOT NULL, `tanggal` DATE NOT NULL, `porsi_dihabiskan` ENUM('habis', 'sebagian', 'tidak') NOT NULL DEFAULT 'habis', `catatan` TEXT, `dicatat_oleh` INTEGER, `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`jadwal_pmt_id`) REFERENCES `jadwal_pmt` (`id`) ON DELETE CASCADE ON UPDATE CASCADE, FOREIGN KEY (`balita_id`) REFERENCES `balita` (`id`) ON DELETE NO ACTION ON UPDATE CASCADE, FOREIGN KEY (`dicatat_oleh`) REFERENCES `users` (`id`) ON DELETE SET NULL ON UPDATE CASCADE) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `jadwal_posyandu`;
CREATE TABLE IF NOT EXISTS `jadwal_posyandu` (`id` INTEGER auto_increment , `wilayah_posyandu_id` INTEGER NOT NULL, `tanggal` DATE NOT NULL, `jam_mulai` TIME, `jam_selesai` TIME, `lokasi` VARCHAR(255), `kegiatan` VARCHAR(255), `keterangan` TEXT, `status` ENUM('terjadwal', 'selesai', 'dibatalkan') NOT NULL DEFAULT 'terjadwal', `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`wilayah_posyandu_id`) REFERENCES `wilayah_posyandu` (`id`) ON DELETE CASCADE ON UPDATE CASCADE) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `kunjungan_posyandu`;
CREATE TABLE IF NOT EXISTS `kunjungan_posyandu` (`id` INTEGER auto_increment , `jadwal_posyandu_id` INTEGER NOT NULL, `balita_id` INTEGER NOT NULL, `pengukuran_id` INTEGER, `catatan` TEXT, `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`jadwal_posyandu_id`) REFERENCES `jadwal_posyandu` (`id`) ON DELETE CASCADE ON UPDATE CASCADE, FOREIGN KEY (`balita_id`) REFERENCES `balita` (`id`) ON DELETE CASCADE ON UPDATE CASCADE, FOREIGN KEY (`pengukuran_id`) REFERENCES `pengukuran` (`id`) ON DELETE SET NULL ON UPDATE CASCADE) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `catatan_pemeriksaan`;
CREATE TABLE IF NOT EXISTS `catatan_pemeriksaan` (`id` INTEGER auto_increment , `balita_id` INTEGER NOT NULL, `dokter_id` INTEGER NOT NULL, `tanggal` DATE NOT NULL, `keluhan` TEXT, `diagnosa` VARCHAR(255), `tindakan` TEXT, `catatan` TEXT, `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`balita_id`) REFERENCES `balita` (`id`) ON DELETE CASCADE ON UPDATE CASCADE, FOREIGN KEY (`dokter_id`) REFERENCES `users` (`id`) ON DELETE NO ACTION ON UPDATE CASCADE) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `rekomendasi_dokter`;
CREATE TABLE IF NOT EXISTS `rekomendasi_dokter` (`id` INTEGER auto_increment , `balita_id` INTEGER NOT NULL, `status_gizi_id` INTEGER, `dokter_id` INTEGER NOT NULL, `isi_rekomendasi` TEXT NOT NULL, `tanggal` DATE NOT NULL, `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`balita_id`) REFERENCES `balita` (`id`) ON DELETE CASCADE ON UPDATE CASCADE, FOREIGN KEY (`status_gizi_id`) REFERENCES `status_gizi` (`id`) ON DELETE SET NULL ON UPDATE CASCADE, FOREIGN KEY (`dokter_id`) REFERENCES `users` (`id`) ON DELETE NO ACTION ON UPDATE CASCADE) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `notifikasi`;
CREATE TABLE IF NOT EXISTS `notifikasi` (`id` INTEGER auto_increment , `user_id` INTEGER NOT NULL, `judul` VARCHAR(200) NOT NULL, `pesan` TEXT NOT NULL, `tipe` VARCHAR(50) COMMENT 'info, warning, danger, jadwal', `referensi_id` VARCHAR(100), `sudah_dibaca` TINYINT(1) DEFAULT false, `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE ON UPDATE CASCADE) ENGINE=InnoDB;;

DROP TABLE IF EXISTS `log_aktivitas`;
CREATE TABLE IF NOT EXISTS `log_aktivitas` (`id` INTEGER auto_increment , `user_id` INTEGER, `aksi` VARCHAR(100) NOT NULL, `modul` VARCHAR(100) NOT NULL, `detail` TEXT, `ip_address` VARCHAR(50), `created_at` DATETIME NOT NULL, `updated_at` DATETIME NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE SET NULL ON UPDATE CASCADE) ENGINE=InnoDB;;

